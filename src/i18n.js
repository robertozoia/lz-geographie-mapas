let current = 'en';

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : 'en';
  document.documentElement.lang = current;
}

export const getLang = () => current;

export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// Random pick among "|"-separated variants (used for praise messages).
export function tPick(key, vars) {
  const options = t(key, vars).split('|');
  return options[Math.floor(Math.random() * options.length)];
}

export const name = (item) => item.n[current];

// Label for an item's category, e.g. "River" or "Ocean".
export function kindLabel(item) {
  if (item.cat === 'sea' && item.kind === 'ocean') return t('one.ocean');
  return t('one.' + item.cat);
}

// Comparable form of a name: lowercase, no accents, ß → ss.
export function normalize(s) {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '')
    .toLowerCase().replace(/ß/g, 'ss').replace(/[^a-z0-9]+/g, ' ').trim();
}

// Guess a starting language from the browser for the profile screen.
export function browserLang() {
  const l = (navigator.language || 'en').slice(0, 2);
  return LANGS.includes(l) ? l : 'en';
}

// Speak a name in the current language, if a voice is available.
export function speak(text) {
  if (!('speechSynthesis' in window)) return false;
  const u = new SpeechSynthesisUtterance(text);
  u.lang = SPEECH_LANG[current];
  const voice = speechSynthesis.getVoices().find((v) => v.lang.startsWith(current));
  if (voice) u.voice = voice;
  u.rate = 0.9;
  speechSynthesis.cancel();
  speechSynthesis.speak(u);
  return true;
}

export const canSpeak = () => 'speechSynthesis' in window;
